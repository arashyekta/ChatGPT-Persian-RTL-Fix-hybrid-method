// ==UserScript==
// @name         ChatGPT Hybrid BiDi Fix
// @namespace    https://github.com/arashyekta/ChatGPT-Persian-RTL-Fix-hybrid-method
// @version      1.0.1
// @description  Hybrid RTL/LTR and BiDi fix for ChatGPT using model-side direction markers and a browser userscript.
// @author       Arash Yekta
// @license      MIT
//
// @homepageURL  https://github.com/arashyekta/ChatGPT-Persian-RTL-Fix-hybrid-method
// @supportURL   https://github.com/arashyekta/ChatGPT-Persian-RTL-Fix-hybrid-method/issues
//
// @downloadURL  https://raw.githubusercontent.com/arashyekta/ChatGPT-Persian-RTL-Fix-hybrid-method/main/ChatGPT-Persian-RTL-Fix-hybrid-method.user.js
// @updateURL    https://raw.githubusercontent.com/arashyekta/ChatGPT-Persian-RTL-Fix-hybrid-method/main/ChatGPT-Persian-RTL-Fix-hybrid-method.user.js
//
// @match        https://chatgpt.com/*
// @run-at       document-start
// @grant        none
// ==/UserScript==
(() => {
    'use strict';


    /* =========================================================
       Markers generated by ChatGPT
       ========================================================= */

    const RTL_MARKER = '[[RTL]]';
    const LTR_MARKER = '[[LTR]]';


    /* =========================================================
       CSS
       ========================================================= */

    const style = document.createElement('style');

    style.textContent = `
        [data-explicit-dir="rtl"] {
            direction: rtl !important;
            text-align: right !important;
            unicode-bidi: isolate !important;
        }

        [data-explicit-dir="ltr"] {
            direction: ltr !important;
            text-align: left !important;
            unicode-bidi: isolate !important;
        }

        /*
         * Inline code inside RTL text stays LTR.
         */
        [data-explicit-dir="rtl"] code {
            direction: ltr !important;
            unicode-bidi: isolate !important;
            display: inline-block !important;
        }
    `;

    document.documentElement.appendChild(style);


    /* =========================================================
       ChatGPT normal text blocks
       ========================================================= */

    const selectors = [
        'main p',
        'main li',
        'main blockquote',

        'main h1',
        'main h2',
        'main h3',
        'main h4',
        'main h5',
        'main h6',

        'main td',
        'main th'
    ].join(',');


    /* =========================================================
       Helpers
       ========================================================= */

    function isExcludedNode(node) {

        const parent =
            node.parentElement;

        if (!parent) {
            return false;
        }

        return !!parent.closest(
            'pre, code, kbd, samp, [contenteditable="true"]'
        );
    }


    function getTextNodes(el) {

        const nodes = [];

        const walker =
            document.createTreeWalker(
                el,
                NodeFilter.SHOW_TEXT
            );

        let node;

        while ((node = walker.nextNode())) {

            /*
             * Inline code is deliberately excluded from
             * marker detection/removal.
             */
            if (isExcludedNode(node)) {
                continue;
            }

            nodes.push(node);
        }

        return nodes;
    }


    function getCombinedText(nodes) {

        return nodes
            .map(node => node.data)
            .join('');
    }


    /* =========================================================
       Detect direction marker

       NEW in 3.3.0:

       We detect markers not only at the beginning of the
       whole element, but also at the beginning of visual lines.

       This fixes structures such as:

       متن فارسی:

       [[RTL]]- line one
       [[RTL]]- line two
       [[RTL]]- line three

       when ChatGPT renders all those lines inside ONE <p>.
       ========================================================= */

    function detectMarker(el) {

        /*
         * innerText preserves rendered line breaks much better
         * than textContent, including <br> based lines.
         */
        const visibleText =
            el.innerText ||
            el.textContent ||
            '';


        /*
         * Marker at the beginning of a logical/rendered line.
         */
        const lineRegex =
            /(?:^|\n)[\s\u200E\u200F\u2066\u2067\u2068\u2069\uFEFF]*\[\[(RTL|LTR)\]\]/g;


        const directions = [];

        let match;

        while (
            (match = lineRegex.exec(visibleText))
        ) {

            directions.push(
                match[1].toLowerCase()
            );
        }


        /*
         * Normal case:
         * at least one line marker was found.
         */
        if (directions.length) {

            /*
             * If all line markers agree, use that direction.
             */
            const unique =
                [...new Set(directions)];


            if (unique.length === 1) {

                return {
                    direction: unique[0]
                };
            }


            /*
             * Mixed markers in the same DOM block are unusual.
             * Use the first explicit direction rather than
             * guessing from the language.
             */
            return {
                direction: directions[0]
            };
        }


        /*
         * Fallback for simple blocks where innerText behavior
         * differs during streaming.
         */

        const nodes =
            getTextNodes(el);

        if (!nodes.length) {
            return null;
        }


        const text =
            getCombinedText(nodes);


        const prefix =
            text.match(
                /^[\s\u200E\u200F\u2066\u2067\u2068\u2069\uFEFF]*/
            );


        const start =
            prefix
                ? prefix[0].length
                : 0;


        if (
            text.slice(
                start,
                start + RTL_MARKER.length
            ) === RTL_MARKER
        ) {

            return {
                direction: 'rtl'
            };
        }


        if (
            text.slice(
                start,
                start + LTR_MARKER.length
            ) === LTR_MARKER
        ) {

            return {
                direction: 'ltr'
            };
        }


        return null;
    }


    /* =========================================================
       Remove ALL markers

       NEW in 3.3.0:

       Removes repeated markers inside the same paragraph:

       [[RTL]]...
       [[RTL]]...
       [[RTL]]...

       Also works if React splits a marker between text nodes.
       ========================================================= */

    function removeAllMarkers(el) {

        let safety = 0;


        while (safety < 100) {

            safety++;


            const nodes =
                getTextNodes(el);


            if (!nodes.length) {
                return;
            }


            const combined =
                getCombinedText(nodes);


            const rtlIndex =
                combined.indexOf(
                    RTL_MARKER
                );


            const ltrIndex =
                combined.indexOf(
                    LTR_MARKER
                );


            let marker = null;
            let markerStart = -1;


            if (
                rtlIndex !== -1 &&
                (
                    ltrIndex === -1 ||
                    rtlIndex < ltrIndex
                )
            ) {

                marker =
                    RTL_MARKER;

                markerStart =
                    rtlIndex;

            } else if (
                ltrIndex !== -1
            ) {

                marker =
                    LTR_MARKER;

                markerStart =
                    ltrIndex;
            }


            /*
             * No markers left.
             */
            if (
                !marker ||
                markerStart < 0
            ) {
                return;
            }


            const markerEnd =
                markerStart +
                marker.length;


            let position = 0;


            const map =
                nodes.map(node => {

                    const item = {
                        node,
                        start: position,
                        end:
                            position +
                            node.data.length
                    };

                    position =
                        item.end;

                    return item;
                });


            map.forEach(item => {

                const overlapStart =
                    Math.max(
                        markerStart,
                        item.start
                    );


                const overlapEnd =
                    Math.min(
                        markerEnd,
                        item.end
                    );


                if (
                    overlapStart >=
                    overlapEnd
                ) {
                    return;
                }


                const localStart =
                    overlapStart -
                    item.start;


                const localEnd =
                    overlapEnd -
                    item.start;


                item.node.data =
                    item.node.data.slice(
                        0,
                        localStart
                    )
                    +
                    item.node.data.slice(
                        localEnd
                    );
            });
        }
    }


    /* =========================================================
       Get actual content container
       ========================================================= */

    function getContentContainer(el) {

        if (
            el.tagName === 'LI'
        ) {

            const paragraph =
                Array
                    .from(el.children)
                    .find(
                        child =>
                            child.tagName === 'P'
                    );


            if (paragraph) {
                return paragraph;
            }
        }


        return el;
    }


    /* =========================================================
       First meaningful direct child
       ========================================================= */

    function getFirstMeaningfulNode(
        container
    ) {

        for (
            const node
            of container.childNodes
        ) {

            if (
                node.nodeType ===
                Node.TEXT_NODE
            ) {

                const text =
                    node.data
                        .replace(
                            /[\u200E\u200F\u2066\u2067\u2068\u2069\uFEFF]/g,
                            ''
                        )
                        .trim();


                if (!text) {
                    continue;
                }
            }


            return node;
        }


        return null;
    }


    /* =========================================================
       RTL leading inline-code edge case

       Example:

       README.md → توضیح فارسی

       Keeps README.md LTR while preserving RTL reading order.
       ========================================================= */

    function fixRtlLeadingInlineCode(el) {

        if (
            el.dataset.explicitDir !==
            'rtl'
        ) {
            return;
        }


        const container =
            getContentContainer(el);


        if (!container) {
            return;
        }


        const firstNode =
            getFirstMeaningfulNode(
                container
            );


        if (
            !firstNode ||
            firstNode.nodeType !==
                Node.ELEMENT_NODE ||
            firstNode.tagName !==
                'CODE'
        ) {
            return;
        }


        const codeElement =
            firstNode;


        let node =
            codeElement.nextSibling;


        let arrowNode =
            null;


        let arrowMatch =
            null;


        while (node) {

            if (
                node.nodeType ===
                Node.TEXT_NODE
            ) {

                const match =
                    node.data.match(
                        /^\s*([→←])\s*/
                    );


                if (match) {

                    arrowNode =
                        node;

                    arrowMatch =
                        match;

                    break;
                }


                if (
                    node.data.trim() === ''
                ) {

                    node =
                        node.nextSibling;

                    continue;
                }
            }


            break;
        }


        if (
            !arrowNode ||
            !arrowMatch
        ) {
            return;
        }


        /*
         * Remove original arrow.
         */

        arrowNode.data =
            arrowNode.data.slice(
                arrowMatch[0].length
            );


        arrowNode.data =
            arrowNode.data.replace(
                /^\s+/,
                ''
            );


        /*
         * Move code identifier to the visual RTL endpoint.
         */

        container.appendChild(
            document.createTextNode(
                ' ← '
            )
        );


        container.appendChild(
            codeElement
        );
    }


    /* =========================================================
       Apply direction
       ========================================================= */

    function applyDirection(el) {

        /*
         * Never modify:
         * - pre/code blocks
         * - keyboard/sample blocks
         * - composer
         */

        if (
            el.closest(
                'pre, kbd, samp, [contenteditable="true"]'
            )
        ) {
            return;
        }


        const result =
            detectMarker(el);


        if (result) {

            el.dataset.explicitDir =
                result.direction;


            el.setAttribute(
                'dir',
                result.direction
            );


            /*
             * Remove every marker contained in this block,
             * not only the first one.
             */
            removeAllMarkers(el);


            if (
                result.direction ===
                'rtl'
            ) {

                fixRtlLeadingInlineCode(
                    el
                );
            }


            return;
        }


        /*
         * Marker already removed.
         * Preserve previously assigned direction.
         */

        if (
            el.dataset.explicitDir ===
            'rtl'
        ) {

            el.setAttribute(
                'dir',
                'rtl'
            );


            fixRtlLeadingInlineCode(
                el
            );


            return;
        }


        if (
            el.dataset.explicitDir ===
            'ltr'
        ) {

            el.setAttribute(
                'dir',
                'ltr'
            );
        }
    }


    /* =========================================================
       Scan
       ========================================================= */

    function update() {

        document
            .querySelectorAll(
                selectors
            )
            .forEach(
                applyDirection
            );
    }


    /* =========================================================
       Watch ChatGPT streaming / rerenders
       ========================================================= */

    let pending = false;


    new MutationObserver(() => {

        if (pending) {
            return;
        }


        pending = true;


        requestAnimationFrame(() => {

            pending = false;

            update();
        });

    }).observe(
        document.documentElement,
        {
            subtree: true,
            childList: true,
            characterData: true
        }
    );


    update();

})();